"""Generate the self-contained frontend module used by frozen builds."""
from pathlib import Path
import base64
import re
import zlib

ROOT = Path(__file__).resolve().parents[1]


def bundle_html(root=ROOT):
    ui = root / 'webui'
    html = (ui / 'index.html').read_text(encoding='utf-8')
    def css(match):
        content = (ui / match[1]).read_text(encoding='utf-8')
        if re.search(r'url\s*\(|@import', content, re.I):
            raise ValueError('External CSS resources must be embedded explicitly')
        return '<style>' + content + '</style>'
    html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', css, html)
    ws = (ui / 'js/ws.js').read_text(encoding='utf-8').replace('export const ws =', 'const ws =')
    app = (ui / 'js/app.js').read_text(encoding='utf-8')
    statement = "import { ws } from './ws.js';"
    if app.count(statement) != 1:
        raise ValueError('Unexpected frontend module imports')
    script = ws + '\n' + app.replace(statement, '')
    script = re.sub(r'</script', r'<\\/script', script, flags=re.I)
    return html.replace('<script type="module" src="js/app.js"></script>', '<script type="module">' + script + '</script>')


if __name__ == '__main__':
    payload = base64.b85encode(zlib.compress(bundle_html().encode('utf-8'), 9))
    target = ROOT / 'core/_embedded_ui.py'
    target.write_text('# Generated by packaging/embed_ui.py; do not edit.\nimport base64\nimport zlib\n\ndef load_html():\n    return zlib.decompress(base64.b85decode(' + repr(payload) + ')).decode("utf-8")\n', encoding='utf-8')
    print('Embedded frontend generated')
