"""
RuneFetch local WebSocket bridge — Phase 2.

Listens on ws://127.0.0.1:8765 for browser extension messages.
Security model:
  • Bound to loopback only — never 0.0.0.0.
  • Every message must carry the per-install shared token generated by RuneFetch.
  • The bridge accepts {token, url} messages only; it never executes commands.
  • Private/loopback target addresses are blocked before queuing.

Thread model:
  asyncio loop runs in a single daemon thread.
  Incoming URLs are posted to self.incoming (queue.Queue) for the Qt
  main thread to drain via the existing 120 ms poll timer.
"""

import asyncio
import json
import logging
import queue as q_module
import threading

from utils import net_guard

_log = logging.getLogger(__name__)

DEFAULT_PORT = 8765


def _is_private(url: str) -> bool:
    """
    True if the URL should be blocked (private/local address) OR cannot be
    safely resolved. Fails CLOSED — an unresolvable host is treated as blocked,
    since it could not be downloaded anyway and may be a rebinding attempt.
    """
    try:
        net_guard.assert_url_allowed(url)
        return False
    except net_guard.BlockedAddressError:
        return True
    except Exception:
        return True


class LocalBridge:
    """
    Loopback WebSocket server for the RuneFetch browser extension.

    Usage::

        bridge = LocalBridge(token="...", port=8765)
        bridge.start()                       # non-blocking
        # In poll timer:
        while not bridge.incoming.empty():
            url, title = bridge.incoming.get_nowait()
            ...
        bridge.stop()                        # on app exit
    """

    def __init__(self, token: str, port: int = DEFAULT_PORT):
        self.token    = token
        self.port     = port
        # Thread-safe queue for the Qt poll timer to drain
        self.incoming: q_module.Queue = q_module.Queue()

        self._thread: threading.Thread | None = None
        self._loop:   asyncio.AbstractEventLoop | None = None
        self._started = False

    # ── Lifecycle ─────────────────────────────────────────────────────────────

    def start(self):
        if self._started:
            return
        self._started = True
        self._thread = threading.Thread(
            target=self._run, daemon=True, name="rf-ws-bridge"
        )
        self._thread.start()

    def stop(self):
        if self._loop and self._loop.is_running():
            self._loop.call_soon_threadsafe(self._loop.stop)

    @property
    def ws_url(self) -> str:
        return f"ws://127.0.0.1:{self.port}"

    # ── asyncio side ──────────────────────────────────────────────────────────

    def _run(self):
        try:
            import websockets  # noqa: F401
        except ImportError:
            _log.warning(
                "RuneFetch bridge disabled — 'websockets' package not installed. "
                "Run: pip install websockets"
            )
            return

        self._loop = asyncio.new_event_loop()
        asyncio.set_event_loop(self._loop)
        try:
            self._loop.run_until_complete(self._serve())
        except Exception as e:
            _log.error("Bridge server crashed: %s", e)
        finally:
            self._loop.close()

    async def _serve(self):
        import websockets

        async with websockets.serve(
            self._handler,
            "127.0.0.1",
            self.port,
            max_size=2 ** 18,   # 256 KB — more than enough for a URL message
        ):
            _log.info("RuneFetch bridge listening on %s", self.ws_url)
            await asyncio.Future()   # run until loop is stopped

    async def _handler(self, websocket):
        """Handle one persistent WebSocket connection (extension background page)."""
        peer = getattr(websocket, "remote_address", "?")
        # Reject cross-site WebSocket connections from ordinary web pages. The
        # legitimate client is the browser extension (chrome-extension:// origin).
        origin = net_guard.get_ws_origin(websocket)
        if not net_guard.ws_origin_allowed(origin):
            _log.warning("Bridge: rejected connection with disallowed Origin %r", origin)
            await websocket.close(1008, "forbidden origin")
            return
        _log.debug("Bridge: connection from %s", peer)
        try:
            async for raw in websocket:
                response = self._process(raw)
                await websocket.send(json.dumps(response))
        except Exception as exc:
            _log.debug("Bridge: connection closed (%s): %s", peer, exc)

    # ── Message processing (called from asyncio thread) ───────────────────────

    def _process(self, raw: str) -> dict:
        """Parse, validate, and enqueue one incoming message."""
        try:
            msg = json.loads(raw)
        except (ValueError, TypeError):
            return {"ok": False, "error": "invalid_json"}

        if not isinstance(msg, dict):
            return {"ok": False, "error": "expected_object"}

        # Token auth — reject before any processing
        if msg.get("token") != self.token:
            _log.debug("Bridge: rejected unauthorised message (token mismatch)")
            return {"ok": False, "error": "unauthorized"}

        # Ping / capability probe from extension
        if msg.get("action") == "ping":
            from core.version import __version__
            return {
                "ok": True,
                "app":     "RuneFetch",
                "version": __version__,
                "port":    self.port,
            }

        url = (msg.get("url") or "").strip()
        if not url:
            return {"ok": False, "error": "no_url"}

        if not url.startswith(("http://", "https://")):
            return {"ok": False, "error": "non_http_url"}

        if _is_private(url):
            _log.warning("Bridge: blocked private-address URL: %s", url[:80])
            return {"ok": False, "error": "private_address_blocked"}

        title = (msg.get("suggestedTitle") or "").strip()
        self.incoming.put_nowait((url, title))
        _log.info("Bridge: queued  %s", url[:100])
        return {"ok": True, "queued": url}
